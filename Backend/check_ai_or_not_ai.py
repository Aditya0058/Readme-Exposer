def check_ai_or_not_ai(readme_content: str):
    import requests
    import os
    from dotenv import load_dotenv

    load_dotenv()

    api_key = os.getenv("YOUR_JEV_API_KEY")
    proxy_url = os.getenv("JEV_PROXY_URL")

    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }

    payload = {
        "model": "jev-latest",
        "state": readme_content,
        "questions": {
            "authorship_category": {
                "type": "choice",
                "instructions": """
                Analyze the provided GitHub README and classify its likely
                authorship process.

                Evaluate the README using the following evidence:

                1. Writing style and structure
                2. Specificity of technical explanations
                3. Relevance to the actual project
                4. Repetition and generic language
                5. Consistency of terminology and tone
                6. Evidence of practical development experience

                Do not make a decision based on a single characteristic.
                Consider the overall pattern of evidence.

                A polished, grammatically correct, or well-structured README
                is not automatically AI-generated.

                A README containing spelling mistakes or informal language
                is not automatically human-written.

                If the evidence is weak, ambiguous, or insufficient,
                select unknown.

                Do not claim certainty about the author or the tools used.
                """,
                "criteria": {
                    "human": "Primarily written by a human",
                    "ai_generated": "Primarily generated by AI",
                    "unknown": "Insufficient evidence to distinguish the categories"
                }
            },

            "project_specific": {
                "type": "noul",
                "instructions": "Does the README contain concrete, specific details about this project's actual implementation, usage, or configuration?"
            },

            "consistency": {
                "type": "noul",
                "instructions": "Is the README internally consistent in terminology, tone, and technical claims?"
            }
        },
    }

    response = requests.post(
        f"{proxy_url}",
        headers=headers,
        json=payload,
    )
    response.raise_for_status()
    answers = response.json()["answers"]
    print("Authorship:", answers["authorship_category"]["choice"])
    print("Project Specific:", answers["project_specific"]["noul"])
    print("Consistency:", answers["consistency"]["noul"])